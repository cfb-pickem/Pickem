CREATE OR REPLACE FUNCTION public.owns_team(p_team_id bigint)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select exists (select 1 from public.teams t
                  where t.team_id = p_team_id and t.user_id = auth.uid());
$function$

