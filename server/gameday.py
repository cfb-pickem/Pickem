_DETAIL = re.compile(r"\b(break (it|that) down|details?|explain|more|full|everything|deep|long version|walk me through)\b", re.I)
_SENT = re.compile(r"(?<=[.!?])\s+(?=\S)")


def wants_detail(q: str) -> bool:
    return bool(_DETAIL.search(q or ""))


def shorten(text: str, q: str = "", cap: int | None = None) -> str:
    """Answer first, whole sentences, one text <= cap chars (300; 700 when he asked for detail)."""
    cap = cap or (DETAIL_CAP if wants_detail(q) else SHORT_CAP)
    t = re.sub(r"\s+", " ", (text or "").replace("**", "")).strip()
    if len(t) <= cap:
        return t
    out = ""
    for s in _SENT.split(t):
        if len(out) + len(s) + (1 if out else 0) > cap:
            break
        out = f"{out} {s}".strip()
    if not out:  # one long first sentence: cut at a clause boundary
        cut = t[:cap]
        out = cut[: max(cut.rfind("; "), cut.rfind(", "))].rstrip(",;") + "." if max(cut.rfind("; "), cut.rfind(", ")) > 60 \
            else cut.rsplit(" ", 1)[0] + "..."
    return out


def first_sentences(text: str, cap: int = 150) -> str:
    return shorten(text, cap=cap)


def combine(parts: list[tuple[str, str]], cap: int = SHORT_CAP) -> str:
    """[(question, reply)] for texts that stacked up in a dead zone -> ONE text: each answer cut to its first
    sentence(s), in the order he asked, the whole thing <= cap + 100 per extra answer (max 500)."""
    parts = [(q, r) for q, r in parts if r]
    if not parts:
        return ""
    if len(parts) == 1:
        return shorten(parts[0][1], parts[0][0])
    total = min(500, cap + 100 * (len(parts) - 1))
    each = max(90, total // len(parts) - 2)
    out = " ".join(facts_only(r, each) for _, r in parts)
    return shorten(out, cap=total)


def facts_only(text: str, cap: int) -> str:
    """The answer sentences of one reply (they carry a number) up to cap; the voice line after them is dropped so a
    combined text stays all answers."""
    sents = [x for x in _SENT.split(re.sub(r"\s+", " ", text or "").strip()) if x]
    keep = []
    for i, x in enumerate(sents):
        if i and not re.search(r"\d", x):
            break
        if keep and len(" ".join(keep + [x])) > cap:
            break
        keep.append(x)
    return shorten(" ".join(keep), cap=cap) if keep else first_sentences(text, cap)
