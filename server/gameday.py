def _now() -> float:
    p = os.environ.get("PICKY_REPLAY_CLOCK")  # replays only (eval/sat_dm.py)
    if p:
        try:
            return float(open(p).read().strip())
        except (OSError, ValueError):
            pass
    return time.time()


def config() -> dict:
    try:
        return json.loads(CONFIG.read_text())
    except (OSError, ValueError):
        return {}


def today_ct() -> str:
    return dt.datetime.fromtimestamp(_now(), CT).strftime("%Y-%m-%d")


def short_for(team: str | None) -> bool:
    """His DMs go out as ONE short text today (he's at a game on a weak signal)."""
    c = config().get(team or "") or {}
    return bool(c.get("short")) and c.get("date") == today_ct()


def games() -> dict:
    return (L.load() or {}).get("games") or {}


def _start(g: dict) -> float:
    try:
        return dt.datetime.fromisoformat(str(g.get("start")).replace("Z", "+00:00")).timestamp()
    except ValueError:
        return 0.0


def active(gs: dict | None = None) -> bool:
    """A game day: something on the board is live, final in the last 14 h, or kicks off within 12 h."""
    now = _now()
    for g in (gs if gs is not None else games()).values():
        st, k = g.get("state"), _start(g)
        if st == "in" or (st == "post" and now - k < 14 * 3600) or (st == "pre" and 0 < k - now < 12 * 3600):
            return True
    return False


def at_game(gs: dict, team: str | None = None) -> dict | None:
    c = config().get(team if team is not None else WHO.get()) or {}
    if not c.get("at") or c.get("date") != today_ct():
        return None
    at = str(c["at"])
    if at in gs:
        return gs[at]
    hit = L.named_games(at, gs)
    return hit[0] if hit else None


