def league_intent(q: str, ctx_teams: list[str] | None = None) -> str | None:
    """League asks with a live twist (pool games in progress): 'if it ended right now where am I' / 'whos in first rn',
    'ackbar's week?'. Only while a pool game is live; otherwise the normal standings/record lanes are exact."""
    t = (q or "").replace("’", "'")
    gs = games()
    pool = set(map(str, (L.load() or {}).get("pool_ids") or []))
    if not any(g.get("state") == "in" for gid, g in gs.items() if gid in pool):
        return None
    if LEAGUE_PLACE.search(t) and ENDED.search(t):
        return "gd_ended"
    if WEEK_ASK.search(t) and not re.search(r"\blast week\b|\bweek \d+\b", t, re.I):
        return "gd_week"
    return None


def intent(q: str, prev: str = "") -> str | None:
    t = (q or "").replace("’", "'")
    gs = games()
    if not gs or not active(gs):
        return None
    if prev and re.fullmatch(r"\W*(why|how come|how|huh|wdym|explain)\W*\??\W*", t, re.I) and re.search(
            r"cover|spread|line|score|winning|up\b|down\b|\?\s*$", prev, re.I):
        pg = _named(prev, gs)
        if pg and pg[0].get("state") in ("in", "post"):
            return "gd_why"  # 'why?' right after a live cover/score ask: the margin vs the number, not a pick card
    own = _intent(t, prev, gs)
    if prev and (_FOLLOW.search(t) or re.match(r"^\W*(and|what about|how about|same for)\b", t, re.I)) \
            and len(t.split()) <= 6 and own in (None, "gd_score"):
        p = _intent(prev.replace("’", "'"), "", gs)  # 'and texas's' after 'lsu qb stats': the same ask, other team
        if p and p not in ("gd_upsets", "gd_whatif"):
            return p
    return own


def _intent(t: str, prev: str, gs: dict) -> str | None:
    named = _named(t, gs)
    if UPSETS.search(t) and not _UPSET_PICK.search(t):
        return "gd_upsets"
    if WHATIF.search(t) and (named or re.search(r"\bcfp\b|\bplayoff\b", t, re.I)) and not re.search(
            r"\b(my|our|league|pool|standings|i|me)\b", t, re.I):
        return "gd_whatif"
    if TV.search(t) and (named or prev):
        return "gd_tv"
    if TOTAL.search(t) and (named or prev or _HERE.search(t)):
        return "gd_total"
    if DRIVE.search(t):
        return "gd_drive"
    if SPREAD.search(t) and not re.search(r"\b(my|our|i|we|league|pool)\b", t, re.I):
        tg = named or ([at_game(gs)] if _HERE.search(t) and at_game(gs) else [])
        pool = set(map(str, (L.load() or {}).get("pool_ids") or []))
        if tg and all(g and g["id"] not in pool for g in tg):  # pool games keep the league-line lanes
            return "gd_spread"
    if BALL.search(t):
        return "gd_ball"
    if HURT.search(t) and (named or _HERE.search(t) or re.search(r"\b(any|anyone|anybody)\b", t, re.I)):
        return "gd_hurt"
    if LAST.search(t) and not re.search(r"\b(my|our|i)\b", t, re.I):
        return "gd_last"
    if STATS.search(t) and (named or _player_games(t, gs) or re.search(r"\b(qb|quarterback|rb|wr)\b", t, re.I)
                            or (prev and _FOLLOW.search(t))) and not re.search(r"\b(my|our|league|standings)\b", t, re.I):
        return "gd_stats"
    if named and not _LEAGUE.search(t) and (SCORE.search(t) or len(t.split()) <= 4):
        return "gd_score"
    if not named and re.search(r"\bwhat'?s good\b|\bwhat'?s on\b|\bon rn\b|\bgood games?\b|\bclose games?\b", t, re.I):
        return "gd_score"
    if _HERE.search(t) and re.search(r"\bscore\b|\bwinning\b|\bup\b|\bdown\b", t, re.I):
        return "gd_score"
    return None


