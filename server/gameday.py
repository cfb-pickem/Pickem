def expand(q: str) -> str:
    """'uga up?' -> 'Georgia up?' (the board names schools; texts use shorthand). 'osu' = Ohio State unless Oregon
    State / Oklahoma State is what the board has live and Ohio State isn't."""
    return _SHORT_RX.sub(lambda m: SHORT[m.group(1).lower()] + ("'s" if q[m.end():m.end() + 2] == "'s" else ""),
                         q or "").replace("'s's", "'s")


def _named(q: str, gs: dict) -> list[dict]:
    q = expand(q)
    hits = L.named_games(q, gs)
    if not hits:
        cities = {}
        for g in gs.values():
            if g.get("city"):
                cities.setdefault(g["city"].lower(), g)
        for c, g in cities.items():
            if len(c) > 3 and re.search(rf"\bin {re.escape(c)}\b", q, re.I):
                hits.append(g)
    return hits


def _player_games(q: str, gs: dict) -> list[tuple[dict, str, str, list]]:
    """(game, team abbr, category, row) for box-score players the text names (last name, 4+ letters, or full)."""
    allw = {w.lower().rstrip("'s") if w.lower().endswith("'s") else w.lower() for w in re.findall(r"[A-Za-z][A-Za-z'\-]+", q)}
    words = {w.lower() for w in re.findall(r"[A-Za-z][A-Za-z'\-]{3,}", q)} - L._COMMON - {
        "yards", "stats", "line", "game", "have", "does", "many", "much", "playing", "doing", "with", "what", "whats",
        "score", "down", "today", "tonight", "thrown", "throw", "picks", "passing", "rushing", "receiving", "against",
        "there", "their", "them", "they", "this", "that", "here", "most", "ended", "lsu's", "qb's"}
    full, last, first = [], [], []
    for g in gs.values():
        if g.get("state") == "pre":
            continue
        for ab, cats in ((g.get("box") or {}).get("players") or {}).items():
            for cat, c in cats.items():
                for row in c["rows"]:
                    parts = re.sub(r",? (Jr\.|Sr\.|II|III|IV)$", "", row[0]).lower().split(" ")
                    if len(parts) < 2:
                        continue
                    hit = (g, ab, cat, row)
                    if parts[-1] in allw and parts[0].replace(".", "") in allw:
                        full.append(hit)  # 'kj jackson', 'jeremiah smith'
                    elif parts[-1] in words and len(parts[-1]) >= 4:
                        last.append(hit)  # 'marchiol', 'leavitt'
                    elif parts[0] in words and len(parts[0]) >= 4 and cat in ("passing", "rushing", "receiving"):
                        first.append(hit)  # 'arch'
    if full:
        return full
    if last:
        return last
    whos = {h[3][0] for h in first}
    return first if len(whos) == 1 else []  # a first name only counts when one player on today's boards has it


