def _nm(t: dict) -> str:
    return t.get("name") or t.get("abbr") or "?"


def _rk(t: dict) -> str:
    r = t.get("rank")
    return f"No. {r} " if r and r <= 25 else ""


_ORD = {1: "1st", 2: "2nd", 3: "3rd", 4: "4th"}


def _qtr(g: dict) -> str:
    """'1:47 left in the 2nd', 'halftime', 'end of the 1st', 'OT'."""
    p, c, nm = g.get("period") or 0, g.get("clock") or "", str(g.get("status_name") or "")
    if "HALFTIME" in nm or "Half" in L.clock_text(g):
        return "halftime"
    q = _ORD.get(p, "OT" if p == 5 else f"{p - 4}OT")
    if "END_PERIOD" in nm or c in ("0:00", "0:0"):
        return f"end of the {q}" if p <= 4 else f"end of {q}"
    return f"{c} left in the {q}" if p <= 4 else f"{c} left in {q}"


def score_line(g: dict, verb: bool = False) -> str:
    a, h = g["away"], g["home"]
    ap, hp = g.get("away_score") or 0, g.get("home_score") or 0
    st = g.get("state")
    if st == "pre":
        tv = f" on {' / '.join(g['broadcasts'][:2])}" if g.get("broadcasts") else ""
        return f"{_nm(a)} at {_nm(h)} hasn't kicked off yet ({L._kick_ct(g.get('start'))}{tv})."
    lead, trail = (a, h) if ap > hp else (h, a)
    hi, lo = max(ap, hp), min(ap, hp)
    if st == "post":
        if ap == hp:
            return f"Final: {_nm(a)} {ap}, {_nm(h)} {hp}."
        return f"Final: {_rk(lead)}{_nm(lead)} {hi}, {_rk(trail)}{_nm(trail)} {lo}."
    when = _qtr(g)
    if ap == hp:
        s = f"{_nm(a)} and {_nm(h)} are " + ("scoreless" if ap == 0 else f"tied {ap}-{ap}") + f", {when}."
    else:
        s = f"{_rk(lead)}{_nm(lead)} {hi}, {_rk(trail)}{_nm(trail)} {lo}, {when}."
    return s


def _games_for(q: str, gs: dict, need_live: bool = False) -> list[dict]:
    t = q.split(" ||| ")[0]
    hits = _named(t, gs)
    if not hits and _HERE.search(t):
        g = at_game(gs)
        hits = [g] if g else []
    if not hits:
        hits = [g for g, *_ in _player_games(t, gs)][:1]
    if not hits:
        pq, pr = PRIOR.get()
        for src in (pq, pr) + tuple(q.split(" ||| ")[1:]):
            hits = _named(src or "", gs)
            if hits:
                break
    if not hits:
        g = at_game(gs)
        hits = [g] if g else []
    if need_live:
        hits = [g for g in hits if g.get("state") in ("in", "post")] or hits
    seen, out = set(), []
    for g in hits:
        if g["id"] not in seen:
            seen.add(g["id"])
            out.append(g)
    return out


def ans_score(q: str, gs: dict) -> str | None:
    t = q.split(" ||| ")[0]
    hits = _games_for(q, gs)
    if not _named(t, gs) and not _HERE.search(t) and re.search(r"\bwhat'?s good\b|\bwhat'?s on\b|\bon rn\b|\bgood games?\b|"
                                                               r"\bclose games?\b", t, re.I):
        live = [g for g in gs.values() if g.get("state") == "in"]
        live.sort(key=lambda g: (0 if (g["away"].get("rank") or g["home"].get("rank")) else 1,
                                 abs((g.get("away_score") or 0) - (g.get("home_score") or 0))))
        if not live:
            return "Nothing's live right now."
        return "Best ones on now: " + " ".join(score_line(g) for g in live[:3])
    if not hits:
        return None
    if re.search(r"\b(did|does) \w+ (win|lose|beat)\b", t, re.I) and hits[0].get("state") == "post":
        g = hits[0]
        named = L.named_games(expand(t), {g["id"]: g})
        a, h = g["away"], g["home"]
        ap, hp = g.get("away_score") or 0, g.get("home_score") or 0
        win, lose = (a, h) if ap > hp else (h, a)
        te = expand(t)
        asked = lambda side: any(re.search(rf"(?<![\w']){re.escape(k)}(?![\w])", te, 0 if cs else re.I)  # noqa: E731
                                 for k, cs in L._name_keys(side))
        lose_q = bool(re.search(r"\b(lose|lost)\b", t, re.I))
        subj_won = asked(win) and not asked(lose) if not lose_q else asked(lose) and not asked(win)
        yes = subj_won if (asked(win) != asked(lose)) else None
        lead = "" if yes is None else ("Yep, " if yes else "Nope, ")
        return (f"{lead}{_nm(win)} beat {_nm(lose)} {max(ap, hp)}-{min(ap, hp)}." if named else score_line(g))
    return " ".join(score_line(g) for g in hits[:2])


def upset_list(gs: dict) -> list[tuple[dict, dict, dict]]:
    out = []
    for g in gs.values():
        if g.get("state") not in ("in", "post") or _start(g) < _now() - 20 * 3600:
            continue
        for s, o in (("away", "home"), ("home", "away")):
            r, ro = g[s].get("rank"), g[o].get("rank")
            mine, theirs = g.get(f"{s}_score") or 0, g.get(f"{o}_score") or 0
            if r and r <= 25 and mine < theirs and (not ro or ro > 25 or ro > r):
                out.append((g, g[s], g[o]))
    out.sort(key=lambda x: (0 if x[0].get("state") == "in" else 1, x[1]["rank"]))
    return out


def ans_upsets(q: str, gs: dict) -> str:
    ups = upset_list(gs)
    if not ups:
        n = sum(1 for g in gs.values() if g.get("state") in ("in", "post") and (g["away"].get("rank") or g["home"].get("rank")))
        return ("No upsets so far: every ranked team that's played is winning or won." if n else
                "No ranked team has kicked off yet, so no upsets.")
    parts = []
    for g, fav, dog in ups[:3]:
        fs, ds = g.get(f"{'away' if fav is g['away'] else 'home'}_score"), g.get(f"{'away' if dog is g['away'] else 'home'}_score")
        if g.get("state") == "post":
            parts.append(f"{_rk(dog)}{_nm(dog)} beat {_rk(fav)}{_nm(fav)} {ds}-{fs} (final)")
        else:
            parts.append(f"{_rk(dog)}{_nm(dog)} leads {_rk(fav)}{_nm(fav)} {ds}-{fs} ({_qtr(g)})")
    more = f" Plus {len(ups) - 3} more." if len(ups) > 3 else ""
    return "Upset watch: " + "; ".join(parts) + "." + more


_CATS = {"passing": ("passing", r"\b(pass\w*|threw|throw\w*|completions?|qb|quarterback|picks thrown|ints?|interceptions?)\b"),
         "rushing": ("rushing", r"\b(rush\w*|run\w*|ran|carries|rb|running back|ground)\b"),
         "receiving": ("receiving", r"\b(receiv\w*|catch\w*|caught|receptions?|wr|targets?)\b")}


def fmt_row(cat: str, labels: list, row: list) -> str:
    d = dict(zip(labels, row[1:]))
    if cat == "passing":
        c, a = (d.get("C/ATT") or "0/0").split("/")
        s = f"{c}-of-{a}, {d.get('YDS', '0')} passing yards, {d.get('TD', '0')} TD, {d.get('INT', '0')} INT"
    elif cat == "rushing":
        s = f"{d.get('CAR', '0')} carries for {d.get('YDS', '0')} yards" + (f", {d['TD']} TD" if d.get("TD") not in (None, "0") else "")
    elif cat == "receiving":
        s = f"{d.get('REC', '0')} catches for {d.get('YDS', '0')} yards" + (f", {d['TD']} TD" if d.get("TD") not in (None, "0") else "")
    else:
        s = ", ".join(f"{v} {k}" for k, v in d.items() if v)
    return s


def _when(g: dict) -> str:
    return "final" if g.get("state") == "post" else _qtr(g)


def _team_abbr(q: str, g: dict) -> str | None:
    q = expand(q)
    for side in ("away", "home"):
        if L.named_games(q, {g["id"]: {**g, "away" if side == "home" else "home": {"name": "~", "abbr": "~"}}}):
            return g[side].get("abbr")
    return None


TEAM_STATS = [(r"\b(3rd|third) downs?\b|\bthird[- ]down\b|\bconversions?\b", "thirdDownEff", "on 3rd down", True),
              (r"\b(4th|fourth) downs?\b", "fourthDownEff", "on 4th down", True),
              (r"\btotal yards\b|\byards\b(?=.*\b(total|team|offense)\b)|\boffense\b", "totalYards", "total yards", False),
              (r"\bturnovers?\b|\bgiveaways?\b", "turnovers", "turnovers", False),
              (r"\btime of possession\b|\btop\b", "possessionTime", "time of possession", False),
              (r"\bpenalt\w*", "totalPenaltiesYards", "penalties-yards", False),
              (r"\bfirst downs?\b|\b1st downs?\b", "firstDowns", "first downs", False),
              (r"\brushing yards\b|\brun game\b", "rushingYards", "rushing yards", False),
              (r"\bpassing yards\b(?!.*\b[A-Z][a-z]+\b)", "netPassingYards", "passing yards", False)]


def _eff(v: str) -> str:
    m = re.fullmatch(r"(\d+)-(\d+)", str(v or ""))
    return f"{m.group(1)}-of-{m.group(2)}" if m else str(v)


def ans_stats(q: str, gs: dict) -> str | None:
    t = q.split(" ||| ")[0]
    pq, _pr = PRIOR.get()
    for rx, key, lab, eff in TEAM_STATS:
        if re.search(rx, t, re.I) and not _player_games(t, gs):
            hits = _games_for(q, gs, need_live=True)
            if not hits:
                return None
            g = hits[0]
            box = (g.get("box") or {}).get("teams") or {}
            if not box:
                return None
            ab = _team_abbr(t, g)
            name = {g["away"].get("abbr"): _nm(g["away"]), g["home"].get("abbr"): _nm(g["home"])}
            order = [ab] + [x for x in box if x != ab] if ab in box else list(box)
            parts = [f"{name.get(x, x)} {(_eff(box[x][key]) if eff else box[x][key])}" for x in order if box.get(x, {}).get(key)]
            if not parts:
                return None
            return f"{lab[0].upper() + lab[1:]}: " + ", ".join(parts) + f" ({_when(g)})."
    pl = _player_games(t, gs)
    if not pl and _FOLLOW.search(t) and pq:  # 'how's their qb doing' / 'and texas's'
        pl = _player_games(pq, gs) if not _named(t, gs) else []
    want = next((c for c, (_, rx) in _CATS.items() if re.search(rx, t, re.I)), None)
    if pl:
        g = pl[0][0]
        who = pl[0][3][0]
        rows = [(cat, row) for gg, ab, cat, row in pl if row[0] == who and gg["id"] == g["id"] and cat in _CATS]
        if want:
            rows = sorted(rows, key=lambda r: r[0] != want)
        if not rows:
            return None
        labels = {cat: (g["box"]["players"][ab][cat]["labels"]) for gg, ab, cat, row in pl if gg["id"] == g["id"]}
        bits = [fmt_row(cat, labels[cat], row) for cat, row in rows[:2]]
        return f"{who}: {'; '.join(bits)} ({_when(g)})."
    # 'lsu qb stats' / 'who ran for the most for uga' / 'how's their qb doing'
    hits = _games_for(q, gs, need_live=True)
    if not hits:
        return None
    g = hits[0]
    players = (g.get("box") or {}).get("players") or {}
    if not players:
        return None
    src = t if _named(t, gs) else (pq + " " + t if pq else t)
    ab = _team_abbr(t, g) or (None if _named(t, gs) else _team_abbr(src, g))
    if not ab and _FOLLOW.search(t) and pq:  # 'and texas's' = the other team than last time
        prev_ab = _team_abbr(pq, g)
        ab = next((x for x in players if x != prev_ab), None) if prev_ab else None
    cat = want or ("passing" if re.search(r"\b(qb|quarterback)\b", src, re.I) else None)
    if not ab or ab not in players:
        return None
    if not cat:
        cat = "passing"
    c = players[ab].get(cat)
    if not c or not c["rows"]:
        return f"No {cat} stats for {_nm(g['home'] if g['home'].get('abbr') == ab else g['away'])} yet ({_when(g)})."
    row = c["rows"][0]
    tail = ""
    if cat == "passing" and len(c["rows"]) > 1:
        tail = f" Also: {c['rows'][1][0]} {fmt_row(cat, c['labels'], c['rows'][1])}."
    return f"{row[0]}: {fmt_row(cat, c['labels'], row)} ({_when(g)}).{tail}"


def ans_drive(q: str, gs: dict) -> str | None:
    hits = _games_for(q, gs, need_live=True)
    if not hits or not hits[0].get("drives"):
        return None
    g = hits[0]
    dr = g["drives"]
    done = [d for d in dr if not d.get("live")]
    cur = next((d for d in dr if d.get("live")), None)
    name = {g["away"].get("abbr"): _nm(g["away"]), g["home"].get("abbr"): _nm(g["home"])}
    out = []
    if done:
        d = done[-1]
        res = (d.get("result") or "").lower() or "no result yet"
        out.append(f"{name.get(d['team'], d['team'])} went {d.get('description') or '?'}" + (f", ended in a {res}" if res else "") + ".")
    if cur and cur.get("plays"):
        out.append(f"Now {name.get(cur['team'], cur['team'])} has it: {cur.get('description')} so far"
                   + (f", {g['down_distance']}" if g.get("down_distance") else "") + ".")
    out.append(score_line(g))
    return " ".join(out)


def ans_total(q: str, gs: dict) -> str | None:
    hits = _games_for(q, gs)
    if not hits:
        return None
    g = hits[0]
    if g.get("state") == "pre":
        ou = (g.get("odds") or {}).get("over_under")
        return f"{_nm(g['away'])}-{_nm(g['home'])} hasn't started" + (f"; the total is {ou:g}." if ou is not None else ".")
    tot = (g.get("away_score") or 0) + (g.get("home_score") or 0)
    ou = (g.get("odds") or {}).get("over_under")
    if ou is None:
        return f"{tot} points so far in {_nm(g['away'])}-{_nm(g['home'])} ({_when(g)}); I don't have a market total on that one."
    if g.get("state") == "post":
        verdict = "went over" if tot > ou else "stayed under" if tot < ou else "pushed"
        return f"{tot} total points, so it {verdict} the {ou:g} (final)."
    rel = (f"already over the {ou:g}" if tot > ou else f"{ou - tot:g} short of the {ou:g} total")
    return f"{tot} points so far ({_nm(g['away'])} {g.get('away_score')}, {_nm(g['home'])} {g.get('home_score')}), {rel}, {_when(g)}."


def ans_spread(q: str, gs: dict) -> str | None:
    """A non-pool game vs ESPN's pregame market line (the poller keeps it after ESPN hides it at kickoff)."""
    hits = _games_for(q, gs)
    if not hits:
        return None
    g = hits[0]
    od = g.get("odds") or {}
    m = re.match(r"\s*(.+?)\s+(-\d+(?:\.\d+)?)\s*$", str(od.get("details") or ""))
    if not m:
        return f"I don't have a market line on {_nm(g['away'])}-{_nm(g['home'])}. {score_line(g)}"
    fav_ab, num = m.group(1), float(m.group(2))
    fav = g["home"] if fav_ab in (g["home"].get("abbr"), g["home"].get("name")) else g["away"]
    dog = g["away"] if fav is g["home"] else g["home"]
    if g.get("state") == "pre":
        return f"{_nm(fav)} {num:g} (market, total {od.get('over_under')}). Hasn't kicked off."
    fs = g.get("home_score" if fav is g["home"] else "away_score") or 0
    ds = g.get("away_score" if fav is g["home"] else "home_score") or 0
    margin = fs - ds + num  # > 0: the favorite is covering
    who = f"{_nm(fav)} {num:g} is covering" if margin > 0 else f"{_nm(dog)} +{-num:g} is covering" if margin < 0 else "it's a push right now"
    by = f" by {abs(margin):g}" if margin else ""
    return f"Market line {_nm(fav)} {num:g}: {who}{by} ({_nm(fav)} {'up' if fs > ds else 'down' if fs < ds else 'tied'}" \
           f"{' ' + str(abs(fs - ds)) if fs != ds else ''}, {_when(g)})."


