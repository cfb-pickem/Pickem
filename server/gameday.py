"""
Game-day DM lanes (Saturday 11/21 drill, 2026-11-17): answers about ALL of college football, computed in code from
the live poller's cache (live_games.json: every FBS game on ESPN's board, play-by-play/box score/drives for the ones
that kicked off), so the model only adds one voice line. Facts here are never generated by a model.

  intent(q, prev)       -> kind or None   ("gd_score", "gd_upsets", "gd_stats", "gd_drive", "gd_total", "gd_ball",
                                           "gd_last", "gd_hurt", "gd_tv", "gd_whatif")
  answer(kind, ctx, q)  -> str | None     None = no data for it: the full brain answers instead
  shorten(text, q)      -> one short text (Charlie at a stadium on a weak signal: answer first, <= 300 chars)
  combine(answers)      -> several stacked-up texts answered in one reply

"The game I'm at": PICKY_GAMEDAY_FILE (default cfb-pickem-private/gameday.json, private; team names only):
  {"Chuck P": {"date": "2026-11-21", "at": "<ESPN event id or 'Tennessee'>", "short": true}}
'here / this game / that drive / who has the ball' with no team named = his game that day.
Follow-ups ('and the over?', 'how's their QB', 'what channel', 'and Texas's?') resolve against the earlier turn
(PRIOR: the previous text + Picky's last reply), set by group_chat before routing.
"""
