def ans_whatif(q: str, gs: dict) -> str | None:
    c = cfp()
    top = c.get("top") or []
    if not top:
        return None
    t = q.split(" ||| ")[0]
    rel = c.get("released") or "latest"
    if re.search(r"\bwho'?s in\b|\btop (4|four|12|twelve)\b|\bwho would be in\b|\bfield\b", t, re.I):
        return f"CFP top 12 ({rel} rankings): " + ", ".join(f"{r['rank']} {r['team']}" for r in top[:12]) + "."
    hits = _named(t, gs)
    t = expand(t)
    teams = [s for g in hits for s in (g["away"], g["home"]) if any(
        re.search(rf"(?<![\w']){re.escape(k)}(?!\w)", t, 0 if cs else re.I) for k, cs in L._name_keys(s))]
    if not teams:
        ws = re.findall(r"[A-Z][a-zA-Z&]+(?: [A-Z][a-zA-Z&]+)?", t)
        teams = [{"name": w, "location": w} for w in ws]
    out = []
    for tm in teams[:2]:
        nm = tm.get("location") or tm.get("name")
        row = next((r for r in top if r["team"].lower() in {str(tm.get("name", "")).lower(), str(tm.get("location", "")).lower(),
                                                              str(tm.get("short", "")).lower()}), None)
        g = next((g for g in hits if tm in (g["away"], g["home"])), None)
        live = f" Right now: {score_line(g)}" if g and g.get("state") in ("in", "post") else ""
        if row:
            rec = f", {row['record']}" if row.get("record") else ""
            seat = ("inside the top 4 (first-round bye line)" if row["rank"] <= 4 else
                    "inside the 12-team field" if row["rank"] <= 12 else "outside the 12-team field")
            lose = (" A loss would knock them off the bye line and into the at-large crowd." if row["rank"] <= 4 else
                    " A loss puts their at-large spot on the bubble." if row["rank"] <= 12 else "")
            if not re.search(r"\blos", t, re.I):
                lose = ""
            out.append(f"{row['team']} is No. {row['rank']} in the CFP ({rel}{rec}), {seat}.{lose}{live}")
        elif nm:
            out.append(f"{nm} isn't in the CFP top 25 ({rel}), so a loss doesn't move the playoff picture.{live}")
